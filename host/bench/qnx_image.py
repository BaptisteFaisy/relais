#!/usr/bin/env python3
"""QNX 8.0 image building helpers (mission M46), split out of qnx_vm.py.

Everything that talks to the SDP lives here: locating qnxsdp-env.sh (through
the shared detector qnx_env.py), driving mkqnximage, injecting files and boot
commands through the local/snippets/*.custom model, and cross-compiling one C
file with qcc. qnx_vm.py drives the guest itself.

mkifs knowledge baked in below (learned and verified with mkifs -v on this
host, SDP 8.0.0):
  * [+script] is for TEXT scripts (it prepends a shebang); on an ELF binary it
    yields a ~32-byte stub or the entry is silently dropped. Plain entries
    with explicit [perms=0755] are the correct way to embed binaries.
  * mkifs bracket attributes are STICKY across lines: an injected snippet must
    reset [type=file] (it lands after [type=link] lines in the generated
    ifs.build) and restore the ambient [perms=0444] afterwards.
  * Files named without "./" land in /proc/boot/<name>, which is on the stock
    guest PATH (/proc/boot:/system/bin).

Requirement IDs: QNX-07 (image built with the real SDP tooling), QNX-08.
"""
from __future__ import annotations

import os
import shlex
import subprocess
from typing import Optional

try:  # package layout
    from .qnx_env import DEFAULT_ROOTS, find_sdp
except ImportError:  # flat script layout
    from qnx_env import DEFAULT_ROOTS, find_sdp

ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))


class QnxVmError(RuntimeError):
    """Any failure of the QNX VM/image layer, with an actionable message."""


def sdp_env_script() -> str:
    """Path of qnxsdp-env.sh, found through the shared detector."""
    sdp = find_sdp(DEFAULT_ROOTS)
    if not sdp:
        raise QnxVmError("no QNX SDP found (see host/bench/qnx_env.py)")
    script = os.path.join(sdp, "qnxsdp-env.sh")
    if not os.path.exists(script):
        raise QnxVmError(f"{script} missing: SDP install incomplete")
    return script


def run_mkqnximage(vm_dir: str, args: list[str], timeout: int = 900,
                   env_script: Optional[str] = None) -> str:
    """Run one mkqnximage invocation inside *vm_dir*; return its output."""
    script = env_script or sdp_env_script()
    os.makedirs(vm_dir, exist_ok=True)
    quoted = " ".join(shlex.quote(a) for a in args)
    shell = f". {shlex.quote(script)} >/dev/null 2>&1; {quoted}"
    done = subprocess.run(["bash", "-c", shell], cwd=vm_dir,
                          capture_output=True, text=True, timeout=timeout,
                          check=False)
    output = (done.stdout or "") + (done.stderr or "")
    if done.returncode != 0:
        raise QnxVmError(f"mkqnximage {' '.join(args)} failed "
                         f"(exit {done.returncode}):\n{output[-2000:]}")
    return output


def create_vm(vm_dir: str, hostname: str = "relais-m46") -> str:
    """First build: creates local/ and output/ (idempotent afterwards)."""
    return run_mkqnximage(vm_dir, ["mkqnximage", "--type=qemu", "--noprompt",
                                   "--ssh-ident=none", f"--hostname={hostname}"])


def rebuild_vm(vm_dir: str) -> str:
    """Rebuild the image after snippet changes."""
    return run_mkqnximage(vm_dir, ["mkqnximage", "--build", "--noprompt"])


def write_ifs_files(vm_dir: str, entries: dict[str, str]) -> None:
    """Inject {image_name: host_path} via local/snippets/ifs_files.custom.

    See the module docstring for the mkifs rules this respects. Host paths are
    made absolute: the mkifs search list only covers the SDP and the vm dir.
    """
    lines = ["# Generated by host/bench/qnx_image.py (M46) — do not edit.",
             "[type=file]"]
    for name, host in sorted(entries.items()):
        host_abs = os.path.abspath(host)
        if not os.path.exists(host_abs):
            raise QnxVmError(f"file to inject does not exist: {host_abs}")
        lines.append(f"[perms=0755] {name}={host_abs}")
    lines.append("[perms=0444]")
    _write_snippet(vm_dir, "ifs_files.custom", lines)


def write_ifs_start(vm_dir: str, commands: list[str]) -> None:
    """Append boot commands through local/snippets/ifs_start.custom."""
    lines = ["# Generated by host/bench/qnx_image.py (M46) — do not edit."]
    lines += [c for c in commands if c.strip()]
    _write_snippet(vm_dir, "ifs_start.custom", lines)


def _write_snippet(vm_dir: str, name: str, lines: list[str]) -> None:
    path = os.path.join(vm_dir, "local", "snippets", name)
    os.makedirs(os.path.dirname(path), exist_ok=True)
    with open(path, "w", encoding="utf-8") as out:
        out.write("\n".join(lines) + "\n")


def qcc_compile(src: str, out: str, env_script: Optional[str] = None,
                timeout: int = 180, libs: str = "") -> str:
    """Cross-compile one C file for QNX x86_64 with the SDP qcc.

    -D_POSIX_C_SOURCE=200809L is REQUIRED with -std=c11: without it qcc hides
    every POSIX declaration (clock_gettime, strtok_r, ...) — this is also why
    target/ fails to build until M45 lands the same flag.
    """
    script = env_script or sdp_env_script()
    os.makedirs(os.path.dirname(os.path.abspath(out)), exist_ok=True)
    flags = ("-V gcc_ntox86_64 -std=c11 -O2 -Wall -Wextra -Werror -Wshadow "
             "-Wconversion -Wno-sign-conversion -D_POSIX_C_SOURCE=200809L")
    shell = (f". {shlex.quote(script)} >/dev/null 2>&1; "
             f"qcc {flags} {shlex.quote(src)} {libs} -o {shlex.quote(out)}")
    done = subprocess.run(["bash", "-c", shell], capture_output=True,
                          text=True, timeout=timeout, check=False)
    if done.returncode != 0:
        raise QnxVmError(f"qcc failed on {src}:\n{done.stderr[-2000:]}")
    return out
