# ---------------------------------------------------------------------------
# Expansion and arithmetic.
# ---------------------------------------------------------------------------
def safety_codes():
    """Return the F-codes of the safety model (read from host/safety)."""
    model = safety_fmea.parse_fault_model(safety_fmea.TRUTH_TABLE)
    return sorted(model.keys(), key=lambda c: int("".join(ch for ch in c if ch.isdigit())))


def expand(elements, modes):
    """Expand the element/mode tables into one FMEDA row per mode."""
    by_id = {e["id"]: e for e in elements}
    rows = []
    for m in modes:
        element = by_id[m["element"]]
        if m.get("rate_kind") == "combination":
            lam = _combination_rate(element, m["combo_window"])
        else:
            lam = element["lambda_fit"] * m["share"] * element["count"]
        dc = DC_TARGETS[m["dc"]]
        row = dict(m)
        row.setdefault("rate_kind", "share")
        row.setdefault("residual", False)
        row.update({
            "element_name": element["name"],
            "instances": element["count"],
            "lambda_fit": lam,
            "dc_value": dc,
            "element_source": element["source"],
            "element_rationale": element["rationale"],
        })
        row.update(_classify(lam, dc, m["effect"]))
        rows.append(row)
    return rows


def _combination_rate(element, window):
    """Rate of a double fault: lambda^2 of the element times a time window.

    The window is the time during which the two failures must be
    simultaneous: the FTTI for two deaths, the repair time for a second
    fault that strikes while the redundancy is down. Both windows are
    expressed in hours, so that the product stays a rate per hour.
    """
    lam_h = element["lambda_fit"] * element["count"] * 1.0e-9
    if window == "ftti":
        window_h = FTTI_S / 3600.0
    else:
        window_h = REPAIR_TIME_H
    return lam_h * lam_h * window_h * 1.0e9


def _classify(lam, dc, effect):
    """Split a row into the four FMEDA rate classes."""
    detected = lam * dc
    undetected = lam - detected
    if effect == "safe":
        return {"sd": detected, "su": undetected, "dd": 0.0, "du": 0.0}
    return {"sd": 0.0, "su": 0.0, "dd": detected, "du": undetected}


def metrics(rows):
    """Compute the FMEDA metrics from the rows."""
    sd = sum(r["sd"] for r in rows)
    su = sum(r["su"] for r in rows)
    dd = sum(r["dd"] for r in rows)
    du = sum(r["du"] for r in rows)
    total = sd + su + dd + du
    detected = sd + dd
    safe_total = sd + su + dd
    residual = sum(r["lambda_fit"] for r in rows
                   if r.get("residual") and r["effect"] == "dangerous")
    return {
        "sd": sd, "su": su, "dd": dd, "du": du, "total": total,
        "dc": detected / total,
        "sff": detected / safe_total,
        "spf": du / total,
        "spfm": 1.0 - du / total,
        "lfm": 1.0 - su / total,
        "residual": residual,
        "pmhf_fit": du + residual,
    }


def residual_double_fault_rate(elements):
    """Rate of the double faults of the computers (FIT), for the report."""
    rows = expand(elements, [m for m in MODES if m.get("residual")])
    return sum(r["lambda_fit"] for r in rows)


def asil_criteria(m, pmhf_targets):
    """Evaluate the three hardware criteria for each ASIL level."""
    out = {}
    for level in ("D", "C", "B", "A"):
        target = pmhf_targets.get(level)
        checks = [
            ("SPFM", m["spfm"], SPFM_TARGET[level], m["spfm"] >= SPFM_TARGET[level]),
            ("LFM", m["lfm"], LFM_TARGET[level], m["lfm"] >= LFM_TARGET[level]),
        ]
        if target is not None:
            checks.append(("PMHF", m["pmhf_fit"], target, m["pmhf_fit"] < target))
        out[level] = checks
    return out


def reachable_asil(m, pmhf_targets):
    """Return (level, limiting criterion) -- the highest ASIL fully met."""
    criteria = asil_criteria(m, pmhf_targets)
    for level in ("D", "C", "B", "A"):
        failed = [name for name, _v, _t, ok in criteria[level] if not ok]
        if not failed:
            return level, ""
        if level == "A":
            return "below A", failed[0]
    return "below A", "PMHF"


def dominant_rows(rows, key="du", count=5):
    """Return the rows that carry the most of one rate class."""
    ordered = sorted(rows, key=lambda r: -r[key])
    return [r for r in ordered if r[key] > 0.0][:count]
