"""Relais -- quantitative FMEDA model (mission M39).

This module holds the *data* of the FMEDA and the arithmetic that turns it
into the metrics of ISO 26262-5. It reads the failure modes of the safety
model generated by ``host/safety/fmea.py`` (read-only reuse: the F-codes F1..F11
and their official names come from there, they are never typed twice).

Two families of numbers live here, and they are kept apart on purpose:

* **cited** -- the diagnostic-coverage targets (ISO 26262-5:2018, Annex D,
  Table D.2) and the hardware-architectural-metric targets (ISO 26262-2:2018,
  Table 4). The standard is quoted by edition and table; the reader has to
  check the licensed copy, because this demonstrator is not certifiable.
* **HYPOTHESIS** -- every failure rate and every share. No handbook is
  available offline, so each rate is declared as a hypothesis with its
  rationale, and the whole set is bounded by a factor-10 sensitivity sweep
  (``sensitivity.py``).

The mapping of a failure mode to a diagnostic-coverage *class* (high /
medium / low) is engineering judgement: the class values are cited, the
assignment is not.

Standard library only.
"""

