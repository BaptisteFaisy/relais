#!/usr/bin/env python3
"""Relais -- rendering of the quantified FMEDA report (mission M39).

The renderers live here, apart from the model (``model.py``) and the
sensitivity sweep (``sensitivity.py``), so that each file stays small and
readable. The output is deterministic: the same numbers produce the same
bytes.

Standard library only.
"""

from __future__ import annotations

import csv
import io

import model

CSV_COLUMNS = ["Element", "Instances", "F-code", "Failure mode", "Effect",
               "Share", "Lambda [FIT]", "Diagnostic coverage", "Class",
               "Mechanism", "Requirements", "Evidence", "Share source", "Note"]

FOOTNOTE_HYPOTHESIS = ("* every rate of this column is a **HYPOTHESIS** "
                       "(section 3): none of them is a measurement.")


def fit(x):
    """Format a rate in FIT."""
    return f"{x:.1f}"


def rate(x):
    """Format a rate in FIT, in scientific notation when it is tiny."""
    if x > 0.0 and x < 1.0:
        return f"{x:.2e}"
    return f"{x:.1f}"


def pct_small(x):
    """Format a ratio as a percentage, in scientific notation when tiny."""
    value = 100.0 * x
    if 0.0 < value < 0.01:
        return f"{value:.2e} %"
    return f"{value:.2f} %"


def pct(x):
    """Format a ratio as a percentage with two decimals."""
    return f"{100.0 * x:.2f} %"


def klass(row):
    """Return the rate class of a row (SD/SU/DD/DU)."""
    for name in ("sd", "su", "dd", "du"):
        if row[name] > 0.0:
            return name.upper()
    return "--"


def limiting(criteria, level):
    """Return the first criterion that is not met for an ASIL level."""
    for name, _value, _target, ok in criteria[level]:
        if not ok:
            return name
    return "--"


# ---------------------------------------------------------------------------
# Sections of the report.
# ---------------------------------------------------------------------------
def section_standing(out):
    """Header: what the document is and what it is not."""
    out.append("# Relais -- quantified FMEDA (mission M39)")
    out.append("")
    out.append("> **Standing.** Relais is a demonstrator *aligned with* annex 6 "
               "of UN Regulation No. 79. It is **not** compliant, not approved "
               "and not certifiable. This document certifies nothing: it turns "
               "the failure modes of the safety case into numbers, so that the "
               "safety argument can be attacked with numbers.")
    out.append("")
    out.append("Generated by `host/fmeda/fmeda.py`; do not edit by hand. The "
               "failure modes are the ones of the generated FMEA "
               "(`host/safety/fmea.py`, read-only); the diagnostic mechanisms "
               "are the ones that exist in the code, each one quoted with the "
               "file that implements it.")
    out.append("")


def section_scope(out):
    """Scope: what the FMEDA covers and what it deliberately does not."""
    out.append("## 1. Scope and safety goal")
    out.append("")
    out.append("**Safety goal** (from `docs/SAFETY.md` section 1): the actuator "
               "must never stay without a fresh command for longer than a "
               "bounded, measured interval, and it must never apply the "
               "command of a machine that has been deposed.")
    out.append("")
    out.append("**In the model** (random hardware failures): the two QNX "
               "computers, the actuator arbitration controller, the actuator "
               "power path and mechanics, the two machine-actuator links and "
               "the inter-computer link.")
    out.append("")
    out.append("**Out of the model, on purpose** (and therefore *not* covered "
               "by any number of this document):")
    out.append("")
    out.append("- systematic faults and software defects of the two copies of "
               "the same binary (DEG-08): the model counts the *actuation* of "
               "such a defect, never the probability of having written it;")
    out.append("- the timing of the emulated target: every latency of the "
               "bench is measured under emulation (SAFETY.md section 7.5);")
    out.append("- the level-X extensions: a third machine to vote (REP-08), "
               "two actuator channels (ACT-10), a dissimilar backup (DEG-08). "
               "They are listed because they are the way out of the "
               "conclusion of section 5, not because they are counted;")
    out.append("- the security threat model beyond frame authentication "
               "(SAFETY.md section 7.6).")
    out.append("")


def section_method(out, m):
    """Method: the taxonomy, the metrics and the cited criteria."""
    out.append("## 2. Method and criteria")
    out.append("")
    out.append("Each row of the FMEDA is one failure mode of one element. The "
               "rate of the row is")
    out.append("")
    out.append("```text")
    out.append("lambda(row) = lambda(element) * share(mode) * instances(element)")
    out.append("```")
    out.append("")
    out.append("and it is split into the four classes of ISO 26262-5, Table 4:")
    out.append("")
    out.append("| Class | Meaning |")
    out.append("|---|---|")
    out.append("| `SD` | safe failure, detected |")
    out.append("| `SU` | safe failure, undetected (dormant, or latent) |")
    out.append("| `DD` | dangerous failure, detected |")
    out.append("| `DU` | dangerous failure, undetected |")
    out.append("")
    out.append("The diagnostic coverage `DC` of a mode is the probability that "
               "the mechanism detects the failure. The class values are "
               f"**cited**: {model.DC_SOURCE}. The *assignment* of a mechanism "
               "to a class is engineering judgement, and it is listed in the "
               "table of section 4.")
    out.append("")
    section_formulas(out, m)
    section_criteria(out)


def section_formulas(out, m):
    """The formulas of the metrics and the residual term."""
    out.append("The derived metrics are:")
    out.append("")
    out.append("```text")
    out.append("DC    = (SD + DD) / (SD + SU + DD + DU)")
    out.append("SFF   = (SD + DD) / (SD + DD + SU)")
    out.append("SPF   = DU / (SD + SU + DD + DU)")
    out.append("SPFM  = 1 - SPF")
    out.append("LFM   = 1 - SU / (SD + SU + DD + DU)")
    out.append("PMHF  = DU + residual   (the double faults that still reach")
    out.append("                           the dangerous state)")
    out.append("```")
    out.append("")
    out.append(f"The residual multiple-fault term is **computed, not "
               f"neglected**: the double faults of the two computers are "
               f"lambda^2 times a window -- the FTTI "
               f"({model.FTTI_TICKS} ticks = {model.FTTI_S * 1000.0:.0f} ms) "
               f"when both die, the repair time "
               f"({model.REPAIR_TIME_H:.0f} h, **HYPOTHESIS**: no repair data "
               f"is available offline) when the second fault strikes while the "
               f"redundancy is down. It weighs {rate(m['residual'])} FIT, that "
               f"is {pct_small(m['residual'] / m['total'])} of the total, so it "
               f"changes nothing in the conclusion.")
    out.append("")


def section_criteria(out):
    """The cited criteria."""
    out.append("The criteria are **cited**:")
    out.append("")
    out.append(f"- {model.ARCH_SOURCE};")
    out.append("- PMHF targets, quoted with their edition so that the reader "
               "checks the copy in hand: `ISO 26262-2:2018 Table 4` "
               "(A < 1e5, B < 1e6, C < 1e7, D < 1e8 FIT) and "
               "`ISO 26262-4:2009 Table 4` (B < 1e3, C < 1e2, D < 1e1 FIT). "
               "The conclusion of this document does not depend on that "
               "choice: the criterion that decides is SPFM, whose targets are "
               "the same in both editions.")
    out.append("")


def section_inputs(out, elements):
    """The failure-rate inputs and their source."""
    out.append("## 3. Failure-rate inputs")
    out.append("")
    out.append("**No reliability handbook is available to this offline "
               "analysis.** Every rate below is therefore declared as a "
               "HYPOTHESIS, with the rationale that produced it. None of them "
               "is a measurement, and none of them is claimed to be one.")
    out.append("")
    out.append("| Element | Instances | Rate [FIT] | Source | Rationale |")
    out.append("|---|---|---|---|---|")
    for element in elements:
        out.append(f"| {element['id']} -- {element['name']} | "
                   f"{element['count']} | {fit(element['lambda_fit'])} | "
                   f"**{element['source']}** | {element['rationale']} |")
    out.append("")
    out.append("The shares that split an element between its failure modes "
               "are HYPOTHESES as well; they are listed in `docs/FMEDA.csv` "
               "with their own rationale.")
    out.append("")


def section_table(out, rows):
    """The FMEDA table itself."""
    out.append("## 4. FMEDA")
    out.append("")
    out.append("`DC` is the diagnostic-coverage class of the mechanism "
               "(high 99 %, medium 90 %, low 60 %, none 0 %). The class values "
               "are cited, the assignment is judgement. `Lambda` is the rate "
               "of the row, in FIT.")
    out.append("")
    out.append("| Element | F | Failure mode | Effect | Diagnostic mechanism "
               "(requirements) | DC | Lambda [FIT] * | Class |")
    out.append("|---|---|---|---|---|---|---|---|")
    for row in rows:
        out.append(
            f"| {row['element']} | {row['code']} | {row['mode']} | "
            f"{row['effect']} | {row['mechanism']} "
            f"({row['requirements']}) | {row['dc']} | "
            f"{fit(row['lambda_fit'])} | {klass(row)} |")
    out.append("")
    out.append(FOOTNOTE_HYPOTHESIS)
    out.append("")
    out.append("The implementation of each mechanism is quoted in "
               "`docs/FMEDA.csv` (column *Evidence*), so that no mechanism can "
               "be credited without pointing at the code that implements it.")
    out.append("")


def section_notes(out, rows):
    """The notes of the rows that carry the conclusion."""
    out.append("### 4.1 The rows that carry the conclusion")
    out.append("")
    for row in rows:
        if row["du"] > 0.0:
            out.append(f"- **{row['element']} / {row['code']} -- "
                       f"{row['mode']}** ({fit(row['lambda_fit'])} FIT, "
                       f"{fit(row['du'])} FIT of dangerous-undetected). "
                       f"{row['note']} Mechanism: {row['mechanism']}. "
                       f"Implementation: `{row['evidence']}`.")
    out.append("")


def section_metrics(out, m, level, criteria, level_2009, ecu_du):
    """The computed metrics and the ASIL they allow."""
    out.append("## 5. Metrics and reachable ASIL")
    out.append("")
    out.append("| Metric | Value |")
    out.append("|---|---|")
    out.append(f"| lambda SD (safe, detected) | {fit(m['sd'])} FIT |")
    out.append(f"| lambda SU (safe, undetected) | {fit(m['su'])} FIT |")
    out.append(f"| lambda DD (dangerous, detected) | {fit(m['dd'])} FIT |")
    out.append(f"| lambda DU (dangerous, undetected) | {fit(m['du'])} FIT |")
    out.append(f"| lambda total | {fit(m['total'])} FIT |")
    out.append(f"| Diagnostic coverage DC | {pct(m['dc'])} |")
    out.append(f"| Safe failure fraction SFF | {pct(m['sff'])} |")
    out.append(f"| Single point fault share SPF | {pct(m['spf'])} |")
    out.append(f"| SPFM = 1 - SPF | {pct(m['spfm'])} |")
    out.append(f"| LFM | {pct(m['lfm'])} |")
    out.append(f"| Residual (double faults of the computers) | "
               f"{rate(m['residual'])} FIT |")
    out.append(f"| PMHF = lambda DU + residual | {fit(m['pmhf_fit'])} FIT |")
    out.append("")
    section_criteria_table(out, m, level, criteria, level_2009, ecu_du)


def section_criteria_table(out, m, level, criteria, level_2009, ecu_du):
    """The criteria, level by level, and the conclusion."""
    out.append("### Criteria, level by level")
    out.append("")
    out.append("| ASIL | SPFM | LFM | PMHF (2018 targets) | PMHF (2009 targets) "
               "| Limiting criterion | Verdict |")
    out.append("|---|---|---|---|---|---|---|")
    for lvl in ("D", "C", "B", "A"):
        checks = criteria[lvl]
        spfm_ok = next(ok for name, _v, _t, ok in checks if name == "SPFM")
        lfm_ok = next(ok for name, _v, _t, ok in checks if name == "LFM")
        pm18 = next((ok for name, _v, _t, ok in checks if name == "PMHF"), None)
        pm09 = _check_other_edition(m, lvl)
        verdict = "reachable" if lvl == level else "not reachable"
        out.append(f"| {lvl} | {'met' if spfm_ok else 'NOT met'} | "
                   f"{'met' if lfm_ok else 'NOT met'} | "
                   f"{_tri(pm18)} | {_tri(pm09)} | "
                   f"{limiting(criteria, lvl)} | {verdict} |")
    out.append("")
    actuator_du = m["du"] - ecu_du
    out.append(f"**Conclusion: the reachable ASIL of the item, as built, is "
               f"{level}** (with the 2018 PMHF targets; with the 2009 targets "
               f"the answer is {level_2009} -- the same). The limiting "
               f"criterion is the single point fault metric: the actuator is a "
               f"single channel, so its dangerous-undetected failures "
               f"({fit(actuator_du)} FIT of the {fit(m['du'])} FIT of the DU "
               f"class) dominate the metric, and SPFM stays below the ASIL B "
               f"target of {pct(model.SPFM_TARGET['B'])}.")
    out.append("")
    out.append("The architecture of the *protocol* is not the limit: every "
               "failure of the two machines, of the links and of the frames is "
               "detected by a mechanism that exists in the code (section 4). "
               "The limit is the actuator, which the safety concept already "
               "declares a single point of failure (SAFETY.md section 4).")
    out.append("")


def _tri(value):
    """Format a tri-state criterion result."""
    if value is None:
        return "n/a"
    return "met" if value else "NOT met"


def _check_other_edition(m, level):
    """Evaluate the PMHF criterion against the 2009 edition of the target."""
    target = model.PMHF_TARGETS["ISO 26262-4:2009 Table 4"].get(level)
    if target is None:
        return None
    return m["pmhf_fit"] < target


def section_sensitivity(out, results, m):
    """The sensitivity analysis."""
    out.append("## 6. Sensitivity analysis")
    out.append("")
    out.append("Every rate is a HYPOTHESIS, so the conclusion is bounded: each "
               "parameter is multiplied by 10 and by 1/10, and the metrics and "
               "the reachable ASIL are recomputed. The nominal row is the "
               "reference. The two ASIL columns use the two editions of the "
               "PMHF target; when they differ, the PMHF criterion is the one "
               "that decides.")
    out.append("")
    out.append("| Case | DC | SFF | SPF | SPFM | LFM | PMHF [FIT] | "
               "ASIL (2018) | ASIL (2009) |")
    out.append("|---|---|---|---|---|---|---|---|---|")
    out.append(f"| *nominal* | {pct(m['dc'])} | {pct(m['sff'])} | "
               f"{pct(m['spf'])} | {pct(m['spfm'])} | {pct(m['lfm'])} | "
               f"{fit(m['pmhf_fit'])} | -- | -- |")
    for result in results:
        out.append(f"| {result['case']} | {pct(result['dc'])} | "
                   f"{pct(result['sff'])} | {pct(result['spf'])} | "
                   f"{pct(result['spfm'])} | {pct(result['lfm'])} | "
                   f"{fit(result['pmhf'])} | {result['asil']} | "
                   f"{result['asil_2009']} |")
    out.append("")
    out.append("Two rows of that table deserve a comment, because they look "
               "counter-intuitive:")
    out.append("")
    out.append("- `all lambda xN` leaves every ratio untouched and multiplies "
               "the PMHF by N: the conclusion is a statement about ratios, not "
               "about the absolute scale of the hypotheses (the double-fault "
               "rows scale with the square of the rates, but they weigh a few "
               "milli-FIT, so the PMHF follows the linear scale);")
    out.append("- `lambda(ECU) x0.1` *lowers* the SPFM: the computers are a "
               "safe element and the SPFM is a ratio, so making a safe element "
               "rarer shrinks the denominator and makes the dangerous share "
               "relatively bigger. This is a property of the metric, not of "
               "the design, and it is why the PMHF criterion exists next to "
               "the SPFM.")
    out.append("")


def section_inversion(out, inversions):
    """What would have to be true to reach a higher ASIL."""
    out.append("### 6.1 What would have to be true")
    out.append("")
    out.append("| Target | Constraint | Required rate | Hypothesis | Factor |")
    out.append("|---|---|---|---|---|")
    for item in inversions:
        out.append(f"| {item['target']} | {item['constraint']} | "
                   f"{item['required']} | {item['hypothesis']} | "
                   f"{item['factor']} |")
    out.append("")
    out.append("Read the table as the answer to \"what is the cheapest lift\": "
               "the actuator is the single channel, so no amount of work on "
               "the protocol changes these numbers. What changes them is a "
               "runtime diagnostic of the actuation chain (a watchdog on the "
               "arbitration core, a current/speed/position plausibility check "
               "on the power path) and, for the last step, a second "
               "arbitration channel (ACT-10) or a third machine that votes "
               "(REP-08).")
    out.append("")


def section_measure(out):
    """What must be measured on the real target to replace the hypotheses."""
    out.append("## 7. What must be measured on the real target")
    out.append("")
    out.append("Every rate of section 3 is a hypothesis. These are the "
               "measurements that would replace them, in the order that pays:")
    out.append("")
    out.append("1. **Actuation chain failure rate.** Run the actuator on the "
               "real power stage (motor, drive, mechanics, cabling) and count "
               "the failures per hour; then repeat with a current, speed and "
               "position plausibility check, to measure the coverage that "
               "check buys.")
    out.append("2. **Actuator arbitration controller.** Same, with the "
               "watchdog and the self-test that would replace the `none` "
               "coverage of the modes of section 4.1.")
    out.append("3. **Computers.** Failure rate of the QNX computer over a "
               "long campaign, split into the modes of section 4 (death, "
               "freeze, slowness, wrong value, latent).")
    out.append("4. **Links.** Failure rate per link (connector, transceiver, "
               "cable), and the measured detection time of each mechanism "
               "(p+1 ticks, bail_ticks, the two-tick ETAT watchdog) under the "
               "real timing, not under emulation.")
    out.append("5. **Diagnostic coverage.** Measure the coverage of each "
               "mechanism by fault injection on the target: how many corrupted "
               "frames does the CRC-32C / SipHash MAC really catch, how many "
               "wrong values does the order/shadow comparison really catch "
               "when the shadow is not certified, how many silent links does "
               "the bail timer really catch. This is the only way to replace "
               "the `high` / `medium` classes by measured numbers.")
    out.append("6. **Timing.** The FTTI of the will (8 ticks = 40 ms) and the "
               "p+1 detection interval must be measured on the target, with "
               "their distribution, because the whole residual analysis rests "
               "on the FTTI being short.")
    out.append("")


def section_limits(out):
    """The limits of this analysis."""
    out.append("## 8. Limits")
    out.append("")
    out.append("1. The rates are hypotheses, not measurements (section 3); the "
               "sensitivity analysis of section 6 bounds them.")
    out.append("2. The DC classes are cited targets, the assignment is "
               "judgement (section 2).")
    out.append("3. Systematic faults, common to the two copies of the binary, "
               "are outside the random-failure model (DEG-08); the model "
               "counts their *actuation*, not their probability.")
    out.append("4. The PMHF target quoted by edition may differ from the copy "
               "in hand; the conclusion does not depend on it, because SPFM "
               "decides.")
    out.append("5. The residual double-fault term is computed with a repair "
               "time of 1 h (a hypothesis); it is negligible, but it grows "
               "with the repair time and would matter if the machines were "
               "left unattended for weeks.")
    out.append("6. A diagnostic coverage is never invented here: a mechanism "
               "that exists in the code is credited with the class of "
               "ISO 26262-5 Annex D that its behaviour justifies, and a "
               "mechanism that does not exist is credited with nothing.")
    out.append("")


def render_document(rows, elements, m, level, criteria, level_2009,
                    ecu_du, results, inversions):
    """Assemble the whole report."""
    out = []
    section_standing(out)
    section_scope(out)
    section_method(out, m)
    section_inputs(out, elements)
    section_table(out, rows)
    section_notes(out, rows)
    section_metrics(out, m, level, criteria, level_2009, ecu_du)
    section_sensitivity(out, results, m)
    section_inversion(out, inversions)
    section_measure(out)
    section_limits(out)
    return "\n".join(out) + "\n"


def render_csv(rows):
    """Render the FMEDA table as CSV (RFC-4180, deterministic)."""
    buf = io.StringIO()
    writer = csv.writer(buf, lineterminator="\n")
    writer.writerow(CSV_COLUMNS)
    for row in rows:
        writer.writerow([
            row["element"], row["instances"], row["code"], row["mode"],
            row["effect"], f"{row['share']:.4f}", fit(row["lambda_fit"]),
            f"{row['dc']} ({row['dc_value']:.2f})", klass(row),
            row["mechanism"], row["requirements"], row["evidence"],
            row["share_source"], row["note"],
        ])
    return buf.getvalue()
