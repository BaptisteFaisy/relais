#!/usr/bin/env python3
"""Relais -- quantified FMEDA report (mission M39).

Builds the FMEDA of the Relais item from (a) the failure modes already
generated by ``host/safety/fmea.py``, (b) the diagnostic mechanisms that are
really present in the code, and (c) failure rates that are either cited or
declared as HYPOTHESIS. It writes:

  * ``docs/FMEDA.md``  -- the reasoning, the table, the sensitivity analysis
    and the list of what must be measured on the real target,
  * ``docs/FMEDA.csv`` -- the same table, machine readable.

Usage:
  python3 host/fmeda/fmeda.py --out docs/FMEDA.md --csv docs/FMEDA.csv
  python3 host/fmeda/fmeda.py --check      # is docs/FMEDA.md up to date?

Standard library only, deterministic: the same inputs produce the same bytes.
"""

from __future__ import annotations

import argparse
import io
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
if HERE not in sys.path:
    sys.path.insert(0, HERE)

import model  # noqa: E402
import report  # noqa: E402
import sensitivity  # noqa: E402

REPO_ROOT = model.REPO_ROOT
DEFAULT_MD = os.path.join(REPO_ROOT, "docs", "FMEDA.md")
DEFAULT_CSV = os.path.join(REPO_ROOT, "docs", "FMEDA.csv")
ACTUATOR = ("ACT-CTRL", "ACT-PWR")


def build_inversions(elements, modes):
    """Compute what would have to be true to reach ASIL B and ASIL C."""
    out = []
    hypothesis = sum(e["lambda_fit"] for e in elements if e["id"] in ACTUATOR)
    variants = (
        ("ASIL {level}", None),
        ("ASIL {level}, with a runtime diagnostic on the actuator",
         sensitivity.lift_actuator),
    )
    for level in ("B", "C"):
        for template, transform in variants:
            factor, rate, _spfm = sensitivity.max_rate_for_asil(
                elements, modes, ACTUATOR, level, transform)
            out.append({
                "target": template.format(level=level),
                "constraint": f"SPFM >= {report.pct(model.SPFM_TARGET[level])}",
                "required": _required(rate),
                "hypothesis": f"{report.fit(hypothesis)} FIT",
                "factor": _factor(factor),
            })
    out.append({
        "target": "ASIL D",
        "constraint": "SPFM >= 99 % and a third machine to vote",
        "required": ("not reachable: the two computers alone keep "
                     f"{report.fit(ecu_du(elements, modes))} FIT of "
                     "dangerous-undetected failures"),
        "hypothesis": "REP-08 (third machine) and ACT-10 (two channels)",
        "factor": "n/a",
    })
    return out


def _required(rate):
    """Format the required rate of the actuator group."""
    if rate == float("inf"):
        return "no limit from SPFM (the PMHF criterion decides)"
    return f"lambda(ACT-CTRL + ACT-PWR) <= {report.fit(rate)} FIT"


def _factor(factor):
    """Format the factor between the hypothesis and the required rate."""
    if factor == float("inf"):
        return "n/a"
    return f"x{factor:.4g}"


def ecu_du(elements, modes):
    """Dangerous-undetected rate carried by the two computers (FIT)."""
    rows = model.expand(elements, modes)
    return sum(r["du"] for r in rows if r["element"] == "ECU")


def compute(elements=None, modes=None):
    """Compute the whole analysis and return everything the renderers need."""
    elements = elements or model.ELEMENTS
    modes = modes or model.MODES
    rows = model.expand(elements, modes)
    m = model.metrics(rows)
    level, _limiting = model.reachable_asil(
        m, model.PMHF_TARGETS[sensitivity.EDITION_2018])
    level_2009, _l2 = model.reachable_asil(
        m, model.PMHF_TARGETS[sensitivity.EDITION_2009])
    criteria = model.asil_criteria(m, model.PMHF_TARGETS[sensitivity.EDITION_2018])
    results = sensitivity.sweep(elements, modes)
    inversions = build_inversions(elements, modes)
    return {"rows": rows, "metrics": m, "level": level,
            "level_2009": level_2009, "criteria": criteria,
            "sensitivity": results, "inversions": inversions,
            "ecu_du": ecu_du(elements, modes)}


def build_document(result):
    """Render the whole report from a computed result."""
    return report.render_document(
        result["rows"], model.ELEMENTS, result["metrics"], result["level"],
        result["criteria"], result["level_2009"], result["ecu_du"],
        result["sensitivity"], result["inversions"])


def _write(path, text):
    """Write a file, creating the directory if needed."""
    directory = os.path.dirname(path)
    if directory and not os.path.isdir(directory):
        os.makedirs(directory)
    with io.open(path, "w", encoding="utf-8") as fh:
        fh.write(text)


def _read(path):
    """Read a file, or return an empty string when it does not exist."""
    if not os.path.exists(path):
        return ""
    with io.open(path, "r", encoding="utf-8") as fh:
        return fh.read()


def main(argv=None):
    parser = argparse.ArgumentParser(description="Generate the Relais FMEDA.")
    parser.add_argument("--out", default=DEFAULT_MD,
                        help="path of the Markdown report")
    parser.add_argument("--csv", default=DEFAULT_CSV,
                        help="path of the CSV table")
    parser.add_argument("--check", action="store_true",
                        help="only check that the report is up to date")
    args = parser.parse_args(argv)

    result = compute()
    markdown = build_document(result)
    csv_text = report.render_csv(result["rows"])

    if args.check:
        status = 0
        for path, text in ((args.out, markdown), (args.csv, csv_text)):
            if _read(path) != text:
                sys.stderr.write(f"fmeda: {path} is out of date\n")
                status = 1
        return status

    _write(args.out, markdown)
    _write(args.csv, csv_text)
    metrics = result["metrics"]
    sys.stderr.write(
        "fmeda: DC %.2f %%, SFF %.2f %%, SPF %.2f %%, PMHF %.1f FIT, "
        "reachable ASIL %s\n"
        % (100.0 * metrics["dc"], 100.0 * metrics["sff"],
           100.0 * metrics["spf"], metrics["pmhf_fit"], result["level"]))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
