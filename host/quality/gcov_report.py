#!/usr/bin/env python3
"""Human-readable coverage summary from gcov output (stdlib only).

`make coverage` has already produced ``*.gcda``/``*.gcno`` for a ``--coverage``
build.  This script re-runs gcov on each source file of ``--src-dir``, parses
the two facts gcov reports per file — the "Lines executed" percentage and the
exact list of uncovered lines — and emits a Markdown summary.

gcov must run from the repository root with source paths relative to it, so it
can match the relative paths recorded in the .gcno files; the ``.gcov`` file it
writes is read back and removed.

Usage: gcov_report.py --root . --objects build/cov/core --src-dir core/src
                      [--out build/cov/coverage.summary.md]
"""

import argparse
import glob
import os
import re
import subprocess
import sys

# Executable line with a count (some blocks unexecuted -> trailing '*').
COVERED = re.compile(r"^\s*(\d+)\*?:\s*(\d+):")
# Executable line never executed.
UNCOVERED = re.compile(r"^\s*#####:\s*(\d+):(.*)$")
LINE_PCT = re.compile(r"Lines executed:\s*([0-9.]+)% of (\d+)")
BRANCH_PCT = re.compile(r"Branches executed:\s*([0-9.]+)% of (\d+)")


def run_gcov(filepath, objects, root):
    """Run gcov from root; return (lines_pct, lines_total, branch_pct, uncovered)."""
    argv = ["gcov", "-b", "-c", "-o", objects, filepath]
    proc = subprocess.run(argv, cwd=root, stdout=subprocess.PIPE,
                          stderr=subprocess.STDOUT, text=True)
    lines_pct = lines_total = branch_pct = None
    for line in proc.stdout.splitlines():
        match = LINE_PCT.search(line)
        if match:
            lines_pct, lines_total = float(match.group(1)), int(match.group(2))
        match = BRANCH_PCT.search(line)
        if match:
            branch_pct = float(match.group(1))

    gcov_file = os.path.join(root, os.path.basename(filepath) + ".gcov")
    uncovered = []
    if os.path.isfile(gcov_file):
        with open(gcov_file, encoding="utf-8") as handle:
            for line in handle:
                match = UNCOVERED.match(line)
                if match:
                    uncovered.append((int(match.group(1)), match.group(2).strip()))
        os.remove(gcov_file)
    return lines_pct, lines_total, branch_pct, uncovered


def emit_markdown(rows):
    header = ("| file | lines | executed (%) | branches (%) | uncovered lines |\n"
              "|------|-------|--------------|-------------|-----------------|\n")
    body = []
    for name, total, pct, branch, uncovered in rows:
        body.append("| %s | %d | %.2f%% | %s | %d |" % (
            name, total, pct,
            "%.2f%%" % branch if branch is not None else "n/a", uncovered))
    return header + "\n".join(body)


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("--root", required=True)
    parser.add_argument("--objects", required=True)
    parser.add_argument("--src-dir", required=True)
    parser.add_argument("--out", default=None)
    args = parser.parse_args()

    root = os.path.abspath(args.root)
    sources = sorted(glob.glob(os.path.join(args.src_dir, "*.c")))

    rows = []
    detail_blocks = []
    for source in sources:
        rel = os.path.relpath(source, root)
        pct, total, branch, uncovered = run_gcov(rel, args.objects, root)
        rows.append((rel, total or 0, pct or 0.0, branch, len(uncovered)))
        if pct is not None and pct < 100.0:
            block = "## %s — %.2f%% (gcov) — %d uncovered line(s)\n\n" % (
                rel, pct, len(uncovered))
            block += "\n".join("- line %d: `%s`" % (ln, tx)
                               for ln, tx in uncovered)
            detail_blocks.append(block)

    text = "# Coverage summary (auto-generated by gcov_report.py)\n\n"
    text += emit_markdown(rows)
    if detail_blocks:
        text += "\n\n## Uncovered lines by file\n\n" + "\n\n".join(detail_blocks) + "\n"

    if args.out:
        out_path = args.out if os.path.isabs(args.out) else os.path.join(root, args.out)
        os.makedirs(os.path.dirname(out_path), exist_ok=True)
        with open(out_path, "w", encoding="utf-8") as handle:
            handle.write(text)
        print("wrote %s" % out_path)
    else:
        sys.stdout.write(text)
    return 0


if __name__ == "__main__":
    sys.exit(main())