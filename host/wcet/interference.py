#!/usr/bin/env python3
"""interference.py — the pressures a WCET run is measured under (mission M40).

PERF-01 states its budget "under a processor load of lower priority", and the
response-time analysis of docs/TIMING.md needs the *inflation* each neighbour
causes, not a guess. Three pressures are provided, all rate-limited so that two
runs see the same offered load (reproducibility):

  cpu      K busy processes, generated by the probe itself (--burn), so the
           generator is the same portable binary on PC, Pi and QNX;
  journal  a JSON-lines writer at a fixed rate: the journal of spec 6.4 is the
           permanent neighbour of the critical path (OBS-02, actuator side);
  net      UDP datagrams on the loopback at a fixed rate: the frames of spec 6.1
           share the stack and the cache with the measured path.

Nothing here needs root, and nothing here is platform specific: subprocess,
threading, socket and time only (rule 6). The processes are started at the
lowest priority the platform allows WITHOUT root; when that is not possible the
limitation is reported, not hidden (see isolate.sh).
"""
import json
import os
import socket
import subprocess
import sys
import threading
import time

JOURNAL_RATE_HZ = 5000     # lines per second
JOURNAL_LINE_BYTES = 160
NET_RATE_HZ = 2000         # datagrams per second
NET_PAYLOAD_BYTES = 480    # a Relais frame is <= 512 bytes (RELAIS_FRAME_MAX)


def nice_prefix():
    """Lower the priority of a child if the platform allows it without root."""
    if os.name != "posix" or not _have("nice"):
        return []
    return ["nice", "-n", "19"]


def _have(program):
    from shutil import which
    return which(program) is not None


class Interference:
    """Base class: start(), stop(), describe(). Never raises."""

    name = "none"

    def start(self):
        return self

    def stop(self):
        pass

    def describe(self):
        return {"mode": self.name}


class CpuLoad(Interference):
    """K busy processes for `seconds`, spawned by the probe's --burn mode."""

    name = "cpu"

    def __init__(self, probe, workers, seconds):
        self.probe = probe
        self.workers = max(1, int(workers))
        self.seconds = float(seconds)
        self.procs = []

    def start(self):
        prefix = nice_prefix()
        for _ in range(self.workers):
            cmd = prefix + [self.probe, "--burn", "%.3f" % self.seconds]
            try:
                self.procs.append(subprocess.Popen(
                    cmd, stdout=subprocess.DEVNULL, stderr=subprocess.DEVNULL))
            except OSError as exc:
                print("interference: cpu load refused (%s)" % exc, file=sys.stderr)
        return self

    def stop(self):
        for proc in self.procs:
            if proc.poll() is None:
                proc.terminate()
        for proc in self.procs:
            try:
                proc.wait(timeout=5)
            except Exception:
                proc.kill()
        self.procs = []

    def describe(self):
        return {"mode": self.name, "workers": len(self.procs) or self.workers,
                "seconds": self.seconds, "generator": self.probe + " --burn",
                "priority": "nice 19" if nice_prefix() else "default"}


class JournalLoad(Interference):
    """Append JSON lines at a fixed rate, flushing every line."""

    name = "journal"

    def __init__(self, path, rate_hz=JOURNAL_RATE_HZ):
        self.path = path
        self.rate_hz = float(rate_hz)
        self.stop_flag = threading.Event()
        self.thread = None
        self.lines = 0

    def _loop(self):
        period = 1.0 / self.rate_hz
        payload = {"kind": "tick", "detail": "x" * (JOURNAL_LINE_BYTES - 40)}
        line = json.dumps(payload, sort_keys=True)
        next_at = time.monotonic()
        try:
            with open(self.path, "a", encoding="utf-8") as fh:
                while not self.stop_flag.is_set():
                    fh.write(line + "\n")
                    fh.flush()
                    self.lines += 1
                    next_at += period
                    delay = next_at - time.monotonic()
                    if delay > 0:
                        time.sleep(delay)
                    else:
                        next_at = time.monotonic()
        except OSError as exc:
            print("interference: journal load stopped (%s)" % exc, file=sys.stderr)

    def start(self):
        os.makedirs(os.path.dirname(self.path) or ".", exist_ok=True)
        self.thread = threading.Thread(target=self._loop, daemon=True)
        self.thread.start()
        return self

    def stop(self):
        self.stop_flag.set()
        if self.thread is not None:
            self.thread.join(timeout=5)

    def describe(self):
        return {"mode": self.name, "path": self.path, "rate_hz": self.rate_hz,
                "lines_written": self.lines}


class NetLoad(Interference):
    """UDP datagrams on the loopback at a fixed rate (two threads)."""

    name = "net"

    def __init__(self, rate_hz=NET_RATE_HZ, port=0):
        self.rate_hz = float(rate_hz)
        self.port = port
        self.stop_flag = threading.Event()
        self.threads = []
        self.sent = 0
        self.sock = None

    def _pair(self):
        rx = socket.socket(socket.AF_INET, socket.SOCK_DGRAM)
        rx.bind(("127.0.0.1", self.port))
        self.port = rx.getsockname()[1]
        tx = socket.socket(socket.AF_INET, socket.SOCK_DGRAM)
        return rx, tx

    def _sender(self, tx):
        period = 1.0 / self.rate_hz
        payload = b"R" * NET_PAYLOAD_BYTES
        next_at = time.monotonic()
        while not self.stop_flag.is_set():
            try:
                tx.sendto(payload, ("127.0.0.1", self.port))
                self.sent += 1
            except OSError:
                return
            next_at += period
            delay = next_at - time.monotonic()
            if delay > 0:
                time.sleep(delay)
            else:
                next_at = time.monotonic()

    def _receiver(self, rx):
        rx.settimeout(0.2)
        while not self.stop_flag.is_set():
            try:
                rx.recvfrom(65535)
            except socket.timeout:
                continue
            except OSError:
                return

    def start(self):
        try:
            rx, tx = self._pair()
        except OSError as exc:
            print("interference: net load refused (%s)" % exc, file=sys.stderr)
            return self
        self.sock = (rx, tx)
        for target, arg in ((self._sender, tx), (self._receiver, rx)):
            thread = threading.Thread(target=target, args=(arg,), daemon=True)
            thread.start()
            self.threads.append(thread)
        return self

    def stop(self):
        self.stop_flag.set()
        for thread in self.threads:
            thread.join(timeout=2)
        if self.sock is not None:
            for sock in self.sock:
                try:
                    sock.close()
                except OSError:
                    pass

    def describe(self):
        return {"mode": self.name, "rate_hz": self.rate_hz, "port": self.port,
                "datagrams_sent": self.sent, "payload_bytes": NET_PAYLOAD_BYTES}


MODES = {"none": None, "cpu": CpuLoad, "journal": JournalLoad, "net": NetLoad}


def build(mode, ctx):
    """Instantiate one interference. ctx carries probe path, run dir, workers."""
    if mode == "none":
        return Interference()
    if mode == "cpu":
        return CpuLoad(ctx["probe"], ctx["workers"], ctx["seconds"])
    if mode == "journal":
        return JournalLoad(os.path.join(ctx["run_dir"], "journal-load.jsonl"))
    if mode == "net":
        return NetLoad()
    raise ValueError("unknown interference mode: %s" % mode)
